package PatternPrinting;
import java.util.Scanner;
public class Pattern03 {
    public static void main(String[] args){
        Scanner sc=new Scanner(System.in);
        int n=sc.nextInt();
        int num=sc.nextInt();
        for(int i=0;i<n;i++){
            System.out.print(num +" ");
        }

    }
}

